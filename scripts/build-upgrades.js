const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const template = fs.readFileSync(path.join(root, 'src/H5P/description-upgrades.template.js'), 'utf8');
const entities = JSON.parse(fs.readFileSync(path.join(root, 'src/H5P/html-entities.json'), 'utf8'));
const output = '// Generated by npm run build:upgrades. Edit the template, not this file.\n' +
  template.replace('/* HTML_ENTITIES */ {}', JSON.stringify(entities));
fs.writeFileSync(path.join(root, 'upgrades.js'), output);
